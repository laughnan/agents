# Shared helpers for install, doctor, and validators. Source, don't run.

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Cursor reads ~/.cursor/skills, plus ~/.claude/skills and ~/.agents/skills for
# compatibility. ~/.cursor/skills-cursor is Cursor-managed; never install there.
SKILL_DESTS=("$HOME/.claude/skills" "$HOME/.agents/skills" "$HOME/.cursor/skills")

CLAUDE_AGENTS="$HOME/.claude/agents"

CLAUDE_SETTINGS="$HOME/.claude/settings.json"
CLAUDE_MD="$HOME/.claude/CLAUDE.md"
CODEX_AGENTS_MD="$HOME/.codex/AGENTS.md"
CODEX_HOOKS="$HOME/.codex/hooks.json"

SHARED_SETTINGS="$REPO/config/claude/settings.json"
LOCAL_SETTINGS="$REPO/local/claude.settings.json"
LOCAL_AGENTS_MD="$REPO/local/AGENTS.md"

skill_dirs() {
  find "$REPO/skills" -mindepth 2 -maxdepth 2 -name SKILL.md -exec dirname {} \; | sort
}

agent_files() {
  find "$REPO/agents" -maxdepth 1 -type f -name '*.md' | sort
}

# Only own the exact flat absolute target shape install emits. Prefix matching
# alone would also claim links that escape agents/ through ../ or subdirectories.
owned_agent_target() {
  [[ "$1" == "$REPO/agents/"* ]] || return 1
  local name=${1#"$REPO/agents/"}
  [[ "$name" =~ ^[a-z0-9][a-z0-9-]*\.md$ ]]
}

# Shared settings deep-merged with local ones: objects merge, arrays
# concatenate without duplicates, local scalars win. __AGENTS_HOME__ becomes
# the shell-quoted repo path so hook commands survive spaces in the path.
render_claude_settings() {
  local local_json='{}'
  [[ -f "$LOCAL_SETTINGS" ]] && local_json=$(cat "$LOCAL_SETTINGS")
  jq -n -S --slurpfile s "$SHARED_SETTINGS" --argjson l "$local_json" --arg home "$REPO" '
    def dmerge(a; b):
      if (a|type) == "object" and (b|type) == "object" then
        reduce ((a + b) | keys_unsorted[]) as $k ({};
          .[$k] = if (a|has($k)) and (b|has($k)) then dmerge(a[$k]; b[$k])
                  elif (b|has($k)) then b[$k] else a[$k] end)
      elif (a|type) == "array" and (b|type) == "array" then
        reduce (a + b)[] as $x ([]; if any(.[]; . == $x) then . else . + [$x] end)
      else b end;
    dmerge($s[0]; $l) | walk(if type == "string" then gsub("__AGENTS_HOME__"; ($home | @sh)) else . end)'
}

# Run a renderer and print its output only if it succeeded and produced a JSON
# object. Callers must check the status: a failed render must never be written.
render_json_object() {
  local out
  out=$("$@") || return 1
  jq -e 'type == "object"' >/dev/null 2>&1 <<<"$out" || { echo "$1 did not produce a JSON object" >&2; return 1; }
  printf '%s\n' "$out"
}

render_claude_md() {
  echo "<!-- GENERATED by ~/agents/scripts/install. Edit ~/agents/AGENTS.md (or local/AGENTS.md) instead. -->"
  echo "@$REPO/AGENTS.md"
  [[ -f "$LOCAL_AGENTS_MD" ]] && echo "@$LOCAL_AGENTS_MD"
  return 0
}

# Codex has no @-imports: symlink when there's nothing local, else concatenate.
render_codex_agents_md() {
  echo "<!-- GENERATED by ~/agents/scripts/install. Edit ~/agents/AGENTS.md (or local/AGENTS.md) instead. -->"
  cat "$REPO/AGENTS.md"
  printf '\n'
  cat "$LOCAL_AGENTS_MD"
}

strip_orca_codex_hooks() {
  jq '.hooks |= (with_entries(.value |= (map(.hooks |= map(select((.command // "") | test("orca"; "i") | not)))
        | map(select((.hooks | length) > 0))))
      | with_entries(select(.value | length > 0)))' "$CODEX_HOOKS"
}

frontmatter_field() { # file field
  awk -v f="$2" 'NR==1 && $0!="---" {exit} NR>1 && $0=="---" {exit} NR>1 {
    if (index($0, f ":") == 1) { sub("^" f ":[[:space:]]*", ""); print; exit } }' "$1"
}
